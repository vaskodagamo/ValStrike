using System;
using System.Diagnostics;
using System.IO;
using System.Text.RegularExpressions;
using UnrealBuildTool;

public class ValStrike : ModuleRules
{
    public ValStrike(ReadOnlyTargetRules Target) : base(Target)
    {
        PCHUsage = PCHUsageMode.UseExplicitOrSharedPCHs;
        PublicDependencyModuleNames.AddRange(new[] { "Core", "CoreUObject", "Engine" });
        PrivateDependencyModuleNames.AddRange(new[] { "InputCore", "EnhancedInput", "Slate", "SlateCore" });
        WriteBuildInfo(Target);
    }

    // Server version identity (decision 0002): capture the checkout's Git revision at build time
    // in a generated header that only Server/VSServerSubsystem.cpp includes. The header is
    // rewritten only when the revision changes, and HEAD/ref files invalidate UBT's cached
    // makefile so a new commit refreshes it. Uncommitted edits are not reflected.
    private void WriteBuildInfo(ReadOnlyTargetRules Target)
    {
        string ProjectDirectory = Target.ProjectFile != null
            ? Target.ProjectFile.Directory.FullName
            : Path.GetFullPath(Path.Combine(ModuleDirectory, "..", ".."));
        string Revision = Git(ProjectDirectory, "rev-parse HEAD");
        if (Revision == null || !Regex.IsMatch(Revision, "^[0-9a-f]{40}([0-9a-f]{24})?$"))
        {
            Revision = "unknown";
        }

        string OutputDirectory = Path.Combine(ProjectDirectory, "Intermediate", "VSBuildInfo");
        string Header = Path.Combine(OutputDirectory, "VSBuildInfo.h");
        string Content = "#pragma once\n// Generated by ValStrike.Build.cs. Do not edit or commit.\n" +
            "#define VS_SOURCE_REVISION TEXT(\"" + Revision + "\")\n";
        Directory.CreateDirectory(OutputDirectory);
        if (!File.Exists(Header) || File.ReadAllText(Header) != Content)
        {
            File.WriteAllText(Header, Content);
        }
        PrivateIncludePaths.Add(OutputDirectory);

        string Branch = Git(ProjectDirectory, "symbolic-ref -q HEAD");
        string[] GitFiles = { "HEAD", "packed-refs", Branch };
        foreach (string GitFile in GitFiles)
        {
            if (string.IsNullOrEmpty(GitFile))
            {
                continue;
            }
            string Location = Git(ProjectDirectory, "rev-parse --git-path " + GitFile);
            if (Location == null)
            {
                continue;
            }
            string FullPath = Path.GetFullPath(Path.Combine(ProjectDirectory, Location));
            if (File.Exists(FullPath))
            {
                ExternalDependencies.Add(FullPath);
            }
        }
    }

    private static string Git(string WorkingDirectory, string Arguments)
    {
        try
        {
            ProcessStartInfo Start = new ProcessStartInfo("git", Arguments)
            {
                WorkingDirectory = WorkingDirectory,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true,
            };
            using (Process Child = Process.Start(Start))
            {
                string Output = Child.StandardOutput.ReadToEnd();
                Child.StandardError.ReadToEnd();
                if (!Child.WaitForExit(10000) || Child.ExitCode != 0)
                {
                    return null;
                }
                return Output.Trim();
            }
        }
        catch (Exception)
        {
            return null;
        }
    }
}
